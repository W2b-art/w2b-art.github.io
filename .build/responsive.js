#!/usr/bin/env node
/* ============================================================
   W2b ART — responsive derivative generator (AVIF + WebP)
   ------------------------------------------------------------
   For each JPEG master (run this AFTER compress.js — this script
   does not touch/overwrite the master itself), generates two
   width variants in both AVIF and WebP as NEW sibling files:
     <name>-800w.avif   <name>-800w.webp
     <name>-1600w.avif  <name>-1600w.webp
   The master JPEG is untouched and stays the <picture>'s <img>
   fallback src — see js/responsive-img.js.

   Also updates js/responsive-manifest.js with an entry per master
   processed (path relative to the repo root, as used in the room
   system's <img src="...">), so wiring a freshly generated image
   into the live site is just running this script — no manual
   markup edit. js/responsive-img.js reads that manifest and only
   emits <picture> markup for images actually listed in it; any
   image not listed renders exactly as a plain <img> today, so
   running this script for a new batch cannot break images that
   don't have derivatives yet.

   Usage (run from the repo root):
     node .build/responsive.js <file-or-folder> [...more]

   This is TOOLING ONLY — nothing in this repo calls it
   automatically, and it is NOT wired into any page by default.
   Standing rule: never run an image pipeline against the live
   /images folder without Guillaume's explicit go-ahead. This
   script has been tested end-to-end only against scratch copies,
   never against /images — see the build report for the test.
   ============================================================ */

const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const WIDTHS = [800, 1600];
const AVIF_QUALITY = 55; // avif needs a lower number than jpeg/webp for comparable visual quality
const WEBP_QUALITY = 72;
const REPO_ROOT = path.resolve(__dirname, "..");
const MANIFEST_PATH = path.join(REPO_ROOT, "js", "responsive-manifest.js");

const args = process.argv.slice(2);
if (args.length === 0) {
  console.error("Usage: node .build/responsive.js <file-or-folder> [...]");
  process.exit(1);
}

function collect(target) {
  const stat = fs.statSync(target);
  if (stat.isDirectory()) {
    return fs
      .readdirSync(target)
      .filter((f) => /\.jpe?g$/i.test(f) && !/-\d+w\.jpe?g$/i.test(f))
      .map((f) => path.join(target, f));
  }
  return [target];
}

function loadManifest() {
  if (!fs.existsSync(MANIFEST_PATH)) return {};
  const src = fs.readFileSync(MANIFEST_PATH, "utf8");
  const m = src.match(/const RESPONSIVE_MANIFEST = (\{[\s\S]*\});/);
  if (!m) return {};
  try {
    return eval("(" + m[1] + ")"); // trusted local build file, not user input
  } catch (e) {
    console.error("Could not parse existing manifest, starting fresh:", e.message);
    return {};
  }
}

function saveManifest(manifest) {
  const header =
    "/* Auto-generated by .build/responsive.js — do not hand-edit.\n" +
    "   Lists which images have AVIF/WebP derivatives and at which\n" +
    "   widths, keyed by the same relative path used in the room\n" +
    "   system's <img src>. js/responsive-img.js only emits <picture>\n" +
    "   markup for images listed here; everything else stays a plain\n" +
    "   <img> — so this file starting empty/partial is always safe. */\n";
  fs.writeFileSync(MANIFEST_PATH, header + "const RESPONSIVE_MANIFEST = " + JSON.stringify(manifest, null, 1) + ";\n");
}

async function makeVariant(file, width) {
  const ext = path.extname(file);
  const base = file.slice(0, -ext.length);
  const avifOut = `${base}-${width}w.avif`;
  const webpOut = `${base}-${width}w.webp`;
  const input = fs.readFileSync(file);
  const meta = await sharp(input).rotate().metadata();
  const targetWidth = Math.min(width, meta.width || width); // never upscale
  await sharp(input).rotate().resize({ width: targetWidth, withoutEnlargement: true }).avif({ quality: AVIF_QUALITY }).toFile(avifOut);
  await sharp(input).rotate().resize({ width: targetWidth, withoutEnlargement: true }).webp({ quality: WEBP_QUALITY }).toFile(webpOut);
  const kb = (p) => (fs.statSync(p).size / 1024).toFixed(0) + " KB";
  console.log(`    ${path.basename(avifOut)}  ${kb(avifOut)}`);
  console.log(`    ${path.basename(webpOut)}  ${kb(webpOut)}`);
}

(async () => {
  const files = args.flatMap(collect);
  const manifest = loadManifest();
  console.log(`Generating responsive AVIF+WebP (${WIDTHS.join("w, ")}w) for ${files.length} master(s):`);
  for (const f of files) {
    console.log(path.basename(f));
    const beforeSize = fs.statSync(f).size;
    const generatedWidths = [];
    for (const w of WIDTHS) {
      try {
        await makeVariant(f, w);
        generatedWidths.push(w);
      } catch (e) {
        console.error(`    FAILED ${f} @${w}w: ${e.message}`);
        process.exitCode = 1;
      }
    }
    if (generatedWidths.length) {
      const key = path.relative(REPO_ROOT, f).split(path.sep).join("/");
      manifest[key] = { widths: generatedWidths, masterKB: Math.round(beforeSize / 1024) };
    }
  }
  saveManifest(manifest);
  console.log(`Manifest updated: ${MANIFEST_PATH}`);
  console.log("Done.");
})();

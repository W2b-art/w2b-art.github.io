/* Responsive image helper for the room system — builds a <picture> with
   AVIF/WebP srcset falling back to the existing JPEG, driven by
   js/responsive-manifest.js (generated by .build/responsive.js).

   Safe by construction: any src NOT listed in the manifest returns a
   plain <img> — today's exact markup, nothing changes on the live site
   until an image actually has derivatives. Once Guillaume's curated set
   is in place and .build/responsive.js has been run on it (explicit
   go-ahead, not automatic), the same room-system code starts serving
   AVIF/WebP for exactly the images that were processed, no further
   markup work needed. */
function buildResponsiveImg(src, alt, widthAttr, heightAttr){
  var img = new Image();
  img.loading = 'lazy';
  img.alt = alt || '';
  img.src = src;
  if (widthAttr) img.width = widthAttr;
  if (heightAttr) img.height = heightAttr;

  var entry = (typeof RESPONSIVE_MANIFEST !== 'undefined') && RESPONSIVE_MANIFEST[src];
  if (!entry || !entry.widths || !entry.widths.length) return img;

  var pic = document.createElement('picture');
  var sizes = '(max-width:820px) 92vw, (max-width:1500px) 60vw, 1200px';
  function srcset(fmt){
    return entry.widths
      .slice().sort(function(a,b){ return a-b; })
      .map(function(w){ return src.replace(/\.(jpe?g)$/i, '-'+w+'w.'+fmt)+' '+w+'w'; })
      .join(', ');
  }
  var avif = document.createElement('source'); avif.type='image/avif'; avif.srcset=srcset('avif'); avif.sizes=sizes;
  var webp = document.createElement('source'); webp.type='image/webp'; webp.srcset=srcset('webp'); webp.sizes=sizes;
  pic.appendChild(avif);
  pic.appendChild(webp);
  pic.appendChild(img);
  return pic;
}
